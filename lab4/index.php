    // 1. Инициализация переменной количества колонок
    // Попробуйте изменить на 0, 2, 3 или 5 для проверки логики
    $columnsCount = 4; 

    // 2. Массив со структурами таблиц (не менее 10 разных элементов)
    // Формат: "C1*C2*C3#C4*C5*C6" (* - разделитель колонок, # - разделитель строк)
    // Данные подобраны так, чтобы имитировать реальные задачи (сотрудники, товары, оценки)
    $tableStructures = [
        // 1. Список сотрудников (ФИО, Должность, Отдел, Стаж)
        "Иванов И.И.*Инженер*Отдел разработки*5 лет#Петров П.П.*Менеджер*Отдел продаж*3 года#Сидоров С.С.*Дизайнер*Маркетинг*2 года",
        
        // 2. Характеристики ноутбуков (Модель, Процессор, ОЗУ, Цена)
        "MacBook Pro*M2 Pro*16 ГБ*150 000 руб.#Dell XPS 15*i7-13700H*32 ГБ*180 000 руб.#Asus Zenbook*Ryzen 9*16 ГБ*120 000 руб.",
        
        // 3. Расписание занятий (Время, Предмет, Аудитория, Преподаватель) - данных меньше чем колонок (будут пустые)
        "09:00*Математика*101#10:40*Физика*205",
        
        // 4. Одиночный элемент (проверка обработки одной ячейки)
        "Системное уведомление: Сервер перезагружен",
        
        // 5. Избыток данных (больше колонок чем задано в $columnsCount) - лишнее должно обрезаться
        "Товар А*Категория 1*Склад 5*Цена 100*Вес 2кг*Гарантия 1 год#Товар Б*Категория 2*Склад 3*Цена 200*Вес 5кг*Гарантия 2 года",
        
        // 6. Пропуск данных в середине строки (пустая ячейка)
        "Заказ №123*Оплачен**Доставлен курьером#Заказ №124*В обработке*Склад Москва*",
        
        // 7. Полностью пустая структура (проверка сообщения "В таблице нет строк")
        "",
        
        // 8. Структура с пустыми строками (разделители есть, данных нет) - проверка "нет строк с ячейками"
        "*#*#*",
        
        // 9. Длинный список ID статусов (много строк, мало колонок)
        "ID-001*Активен#ID-002*Заблокирован#ID-003*На проверке#ID-004*Архив#ID-005*Удален",
        
        // 10. Смешанные данные (текст и числа)
        "Температура*25°C*Норма#Давление*760 мм рт.ст.*Норма#Влажность*45%*Сухо",
        
        // 11. Граничный случай: одна строка с точным количеством колонок
        "Колонка 1*Колонка 2*Колонка 3*Колонка 4"
    ];

    /**
     * Функция формирования содержимого отдельной строки таблицы (<tr>...</tr>)
     * @param string $dataString Строка вида "C1*C2*C3"
     * @param int $cols Требуемое количество колонок
     * @return string HTML код строки или пустая строка
     */
    function getTR($dataString, $cols) {
        // Разбиваем строку на элементы по разделителю "*"
        $cells = explode('*', $dataString);
        
        // Если входная строка пустая, возвращаем пустоту (строка без ячеек не нужна)
        if ($dataString === '') {
            return '';
        }

        $html = '<tr>';
        $cellsAdded = 0;

        // Заполняем ячейки данными из массива, но не более чем $cols
        for ($i = 0; $i < count($cells); $i++) {
            if ($cellsAdded >= $cols) {
                break; // Прерываем, если достигли лимита колонок (лишние данные игнорируются)
            }
            // Используем htmlspecialchars для безопасного вывода текста
            $html .= '<td>' . htmlspecialchars($cells[$i]) . '</td>';
            $cellsAdded++;
        }
        
        // Если данных меньше чем колонок, добавляем пустые ячейки до нужного количества
        for ($i = $cellsAdded; $i < $cols; $i++) {
            $html .= '<td></td>';
        }
        
        $html .= '</tr>';
        
        return $html;
    }

    /**
     * Функция вывода HTML-кода таблицы исходя из её структуры
     * @param string $structure Структура таблицы
     * @param int $tableNumber Номер таблицы для заголовка
     * @param int $cols Количество колонок
     */
    function outputTable($structure, $tableNumber, $cols) {
        echo "<h2>Таблица №{$tableNumber}</h2>";

        // Проверка на неправильное число колонок (глобальное требование)
        if ($cols <= 0) {
            echo '<div class="error-msg">Неправильное число колонок</div>';
            return;
        }

        // Проверка на отсутствие строк в структуре
        if ($structure === '') {
            echo '<div class="warning-msg">В таблице нет строк</div>';
            return;
        }

        // Разбиваем структуру на строки по разделителю "#"
        $rows = explode('#', $structure);
        
        $rowsHtml = '';
        $hasRowsWithCells = false;

        foreach ($rows as $row) {
            // Получаем HTML код для конкретной строки
            $trHtml = getTR($row, $cols);
            
            // Если функция вернула не пустую строку, значит в ней были данные
            if (!empty($trHtml)) {
                $rowsHtml .= $trHtml;
                $hasRowsWithCells = true;
            }
        }

        // Финальная проверка: есть ли хоть одна строка с данными
        if (!$hasRowsWithCells) {
            echo '<div class="warning-msg">В таблице нет строк с ячейками</div>';
        } else {
            echo "<table>";
            echo $rowsHtml;
            echo "</table>";
        }
    }

    // Основной цикл программы: перебор всех структур из массива
    $tableIndex = 1;
    foreach ($tableStructures as $struct) {
        outputTable($struct, $tableIndex, $columnsCount);
        echo "<hr>"; // Визуальный разделитель между таблицами
        $tableIndex++;
    }
